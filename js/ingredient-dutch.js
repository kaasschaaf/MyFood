/**
 * Normalises an ingredient name for lookup.
 * @param {string} value
 * @returns {string}
 */
function normalize(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Translates an English ingredient name to Dutch for AH lookups.
 * @param {string} name
 * @returns {{ text: string, complete: boolean, changed: boolean }}
 *   `complete` means every meaningful word was understood.
 */
export function translateIngredientToDutch(name) {
  const original = String(name || "").trim();
  const normalized = normalize(original);
  if (!normalized) return { text: original, complete: false, changed: false };

  const phrase = PHRASE_LOOKUP.get(normalized);
  if (phrase) return { text: phrase, complete: true, changed: true };

  const words = normalized.split(" ");
  const keywords = words.filter(word => !PREP_WORDS.has(word) && !MEASURE_TOKEN.test(word));
  const stripped = keywords.join(" ");
  if (stripped && PHRASE_LOOKUP.has(stripped)) {
    return { text: PHRASE_LOOKUP.get(stripped), complete: true, changed: true };
  }

  // Only the words we understand end up in the query: AH cannot search
  // "high heat cooking oil", but it finds "zonnebloemolie" straight away.
  let translated = 0;
  let unknown = 0;
  const output = [];
  for (const word of keywords) {
    const match = WORDS[word] || WORDS[word.replace(/s$/, "")];
    if (match) {
      output.push(match);
      translated++;
    } else {
      unknown++;
    }
  }
  if (!translated) return { text: original, complete: false, changed: false };
  return { text: output.join(" ").trim(), complete: unknown === 0, changed: true };
}

